-- 1. Tabel utama -------------------------------------------------
create table if not exists public.courses (
  id         bigint generated by default as identity primary key,
  code       text        not null unique,
  title      text        not null,
  credits    integer     not null,
  status     text        not null default 'planned',
  created_at timestamptz not null default now(),

  constraint courses_code_not_blank  check (length(trim(code)) > 0),
  constraint courses_title_not_blank check (length(trim(title)) > 0),
  constraint courses_credits_positive check (credits > 0),
  constraint courses_status_valid     check (status in ('planned', 'active', 'done'))
);

-- 2. Row Level Security -----------------------------------------
alter table public.courses enable row level security;

drop policy if exists "courses_select_lab" on public.courses;
drop policy if exists "courses_insert_lab" on public.courses;
drop policy if exists "courses_update_lab" on public.courses;
drop policy if exists "courses_delete_lab" on public.courses;

-- Praktikum: client (anon) boleh baca, tambah, ubah, hapus.
create policy "courses_select_lab"
  on public.courses
  for select
  to anon, authenticated
  using (true);

create policy "courses_insert_lab"
  on public.courses
  for insert
  to anon, authenticated
  with check (true);

create policy "courses_update_lab"
  on public.courses
  for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "courses_delete_lab"
  on public.courses
  for delete
  to anon, authenticated
  using (true);

-- 3. Hak akses tabel untuk role client --------------------------
grant select, insert, update, delete on public.courses to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

